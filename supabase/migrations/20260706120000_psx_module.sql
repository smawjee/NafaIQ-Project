GRANT SELECT ON public.psx_ticks TO anon, authenticated;
GRANT ALL ON public.psx_ticks TO service_role;
-- Required for realtime broadcast on inserts
ALTER TABLE public.psx_ticks REPLICA IDENTITY FULL;

-- 9. User watchlist (RLS: users see only their own)
CREATE TABLE IF NOT EXISTS public.psx_watchlist (
    user_id     UUID REFERENCES auth.users(id) ON DELETE CASCADE,
    symbol      TEXT NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY(user_id, symbol)
);
ALTER TABLE public.psx_watchlist ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Users own their watchlist" ON public.psx_watchlist FOR ALL TO authenticated USING (auth.uid() = user_id);
GRANT ALL ON public.psx_watchlist TO authenticated;

