-- 12. Holdings within a portfolio (RLS via parent portfolio join)
CREATE TABLE IF NOT EXISTS public.psx_holdings (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    portfolio_id    BIGINT REFERENCES public.psx_portfolios(id) ON DELETE CASCADE,
    symbol          TEXT NOT NULL,
    shares          BIGINT NOT NULL DEFAULT 0,
    avg_cost        NUMERIC(12,2) NOT NULL DEFAULT 0,
    purchased_at    DATE,
    UNIQUE(portfolio_id, symbol)
);
ALTER TABLE public.psx_holdings ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Users own their holdings through portfolio" 
    ON public.psx_holdings FOR ALL TO authenticated 
    USING (
        EXISTS (
            SELECT 1 FROM public.psx_portfolios 
            WHERE public.psx_portfolios.id = public.psx_holdings.portfolio_id 
            AND public.psx_portfolios.user_id = auth.uid()
        )
    );
GRANT ALL ON public.psx_holdings TO authenticated;
