-- PSX Module Tables
-- Run via supabase db push or manually via Supabase Dashboard

-- 1. Market snapshot (refreshed every 5s during session)
CREATE TABLE IF NOT EXISTS public.psx_market_snapshot (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    symbol      TEXT NOT NULL,
    price       NUMERIC(12,2),
    change      NUMERIC(12,2),
    change_pct  NUMERIC(8,4),
    volume      BIGINT DEFAULT 0,
    day_high    NUMERIC(12,2),
    day_low     NUMERIC(12,2),
    refreshed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE(symbol)
);
CREATE INDEX IF NOT EXISTS idx_psx_ms_sym ON public.psx_market_snapshot(symbol);
CREATE INDEX IF NOT EXISTS idx_psx_ms_refreshed ON public.psx_market_snapshot(refreshed_at DESC);
ALTER TABLE public.psx_market_snapshot ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Public read market snapshot" ON public.psx_market_snapshot FOR SELECT USING (true);
GRANT SELECT ON public.psx_market_snapshot TO anon, authenticated;
GRANT ALL ON public.psx_market_snapshot TO service_role;

